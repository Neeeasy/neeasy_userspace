oled_rotation_t oled_init_user(oled_rotation_t rotation) {
    return OLED_ROTATION_270;
}

bool oled_task_user(void) {
    if (is_keyboard_master()) {
        // ЛЕВАЯ половина — статус слоя и Caps Lock, аккуратным блоком
        oled_write_P(PSTR("VOSKHOD\n"), false);
        oled_write_P(PSTR("-------\n\n"), false);

        oled_write_P(PSTR("LAYER\n"), false);
        switch (get_highest_layer(layer_state)) {
            case _BASE:
                oled_write_P(PSTR(">Base\n"), false);
                break;
            case _NUM:
                oled_write_P(PSTR(">Num\n"), false);
                break;
            case _NAV:
                oled_write_P(PSTR(">Nav\n"), false);
                break;
            default:
                oled_write_P(PSTR(">????\n"), false);
                break;
        }

        oled_write_P(PSTR("\n"), false);

        led_t led_state = host_keyboard_led_state();
        oled_write_P(PSTR("CAPS"), false);
        oled_write_P(led_state.caps_lock ? PSTR("[X]\n") : PSTR("[ ]\n"), false);
    } else {
        // ПРАВАЯ половина — лого МСтрой, статично
        oled_write_raw_P(mstroy_logo, sizeof(mstroy_logo));
    }
    return false;
}

